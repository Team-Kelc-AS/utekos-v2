import { createProcessor } from '@mdx-js/mdx';
import remarkGfm from 'remark-gfm';
import { readdir, readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

export const WORDS_PER_MINUTE = 265;
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const processor = createProcessor({ remarkPlugins: [remarkGfm] });
const omittedTypes = new Set(['mdxjsEsm', 'code', 'html', 'image', 'definition']);
const omittedElements = new Set([
  'header', 'nav', 'figure', 'figcaption', 'script', 'style', 'Image',
  'KnowledgeArticleIntro', 'KnowledgeArticleMeta', 'KnowledgeArticleBreadcrumbs',
  'KnowledgeRegisteredImage', 'ArticleImage', 'EditorialFigure',
  'KnowledgeLearnings', 'KnowledgeToc', 'TableOfContents', 'KnowledgeSources',
  'BackToTop', 'MostReadArticles', 'PageAiSummary', 'Cite', 'ArticleReadingProgress',
]);
const sourceHeading = /^(?:kilder(?:\s*\(\d+\))?|referanser|referanseliste|sources used in the report)$/iu;

function attribute(node, name) {
  return node.attributes?.find(item => item.name === name)?.value;
}

function visibleText(node) {
  if (node.type === 'text' || node.type === 'inlineCode') return node.value;
  return (node.children ?? []).map(visibleText).join('');
}

function findElement(node, name) {
  if (node.name === name) return node;
  for (const child of node.children ?? []) {
    const match = findElement(child, name);
    if (match) return match;
  }
}

function isSources(node) {
  if (node.type === 'heading' && sourceHeading.test(visibleText(node).trim())) return true;
  const id = attribute(node, 'id') ?? attribute(node, 'aria-labelledby');
  if (typeof id === 'string' && /^(?:kilder|referanser|kilde-\d+)$/.test(id)) return true;
  const summary = node.name === 'details' ? findElement(node, 'summary') : undefined;
  return summary ? sourceHeading.test(visibleText(summary).trim()) : false;
}

function readingText(node) {
  if (omittedTypes.has(node.type) || omittedElements.has(node.name) || isSources(node)) return '';
  if (node.type === 'heading' && node.depth === 1) return '';
  const labelledBy = attribute(node, 'aria-labelledby');
  if (labelledBy === 'learning-heading' || labelledBy === 'i-denne-artikkelen') return '';
  if (node.attributes?.some(item => item.name === 'data-reading-exclude')) return '';
  if (node.type === 'text' || node.type === 'inlineCode') return node.value;
  if (node.type === 'mdxTextExpression' || node.type === 'mdxFlowExpression') {
    const expression = node.data?.estree?.body?.[0]?.expression;
    return expression?.type === 'Literal' && typeof expression.value === 'string' ? expression.value : '';
  }
  let text = '';
  for (const child of node.children ?? []) {
    // Everything following a source heading belongs to the bibliography.
    if (child.type === 'heading' && isSources(child)) break;
    text += readingText(child);
  }
  const title = attribute(node, 'title');
  if (typeof title === 'string') text = `${title}\n${text}`;
  return text + (['paragraph', 'heading', 'listItem', 'tableCell', 'tableRow', 'mdxJsxFlowElement'].includes(node.type) ? '\n' : '');
}

export function articleReadingMetrics(markdown) {
  const text = readingText(processor.parse(markdown));
  const wordCount = (text.match(/\S+/gu) ?? []).filter(word => /[\p{L}\p{N}]/u.test(word)).length;
  return { wordCount, readingMinutes: Math.max(1, Math.ceil(wordCount / WORDS_PER_MINUTE)) };
}

export async function buildArticleReadingTimes() {
  const directory = path.join(root, 'src/app/(site)/(blog)/uteguiden');
  const metrics = {};
  for (const entry of (await readdir(directory, { withFileTypes: true })).sort((a, b) => a.name.localeCompare(b.name))) {
    if (!entry.isDirectory()) continue;
    let markdown;
    try { markdown = await readFile(path.join(directory, entry.name, 'page.mdx'), 'utf8'); }
    catch (error) { if (error.code === 'ENOENT') continue; throw error; }
    metrics[entry.name] = articleReadingMetrics(markdown);
    if (metrics[entry.name].wordCount < 100) throw new Error(`Missing article body for ${entry.name}`);
  }
  const target = path.join(root, 'src/lib/knowledge/articleReading.generated.ts');
  const json = '// Generated by scripts/build-article-reading-times.mjs.\nexport default ' + JSON.stringify(metrics, null, 2) + ' as const;\n';
  const previous = await readFile(target, 'utf8').catch(error => { if (error.code === 'ENOENT') return ''; throw error; });
  if (previous !== json) await writeFile(target, json);
  console.log(`Reading time: ${Object.keys(metrics).length} article bodies at ${WORDS_PER_MINUTE} words/minute`);
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) await buildArticleReadingTimes();
